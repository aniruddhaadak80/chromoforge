"""Cross-language parity harness.

Diffs the Python simulation engine against the TypeScript fixtures (the source
of truth) generated by `bun packages/core/scripts/gen-vectors.ts`, and — when
a working linker is available (Linux/macOS/VS Build Tools) — against the Rust
reference engine via its CLI.

Usage:
    python -m parity.run_parity            # python vs typescript
    python -m parity.run_parity --rust      # also run the rust engine
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sim import Environment, SimConfig, SimResult, TraitVector, simulate

FIXTURES = Path(__file__).parent / "fixtures.json"
TOLERANCE = 1e-9


def _snake_case(key: str) -> str:
    out = []
    for ch in key:
        if ch.isupper():
            out.append("_")
            out.append(ch.lower())
        else:
            out.append(ch)
    return "".join(out)


def _normalize_traits(traits: dict) -> dict:
    return {_snake_case(k): v for k, v in traits.items()}


def load_fixtures() -> list[dict]:
    with FIXTURES.open(encoding="utf-8") as fh:
        return json.load(fh)["fixtures"]


def run_python(fixture: dict) -> SimResult:
    inp = fixture["input"]
    traits = TraitVector(**_normalize_traits(inp["traits"]))
    env = Environment(**inp["environment"])
    cfg_in = inp["config"]
    config = SimConfig(
        generations=cfg_in["generations"],
        founders=cfg_in["founders"],
        mutation_std_dev=cfg_in["mutation_std_dev"],
        seed=cfg_in["seed"],
        world_fertility=cfg_in.get("world_fertility"),
    )
    return simulate(traits, env, inp["upkeep"], config)


def compare(result: dict, expected: dict, label: str) -> list[str]:
    errors: list[str] = []
    if result["outcome"] != expected["outcome"]:
        errors.append(
            f"{label}: outcome {result['outcome']!r} != {expected['outcome']!r}"
        )
    if result["extinct_at"] != expected["extinct_at"]:
        errors.append(
            f"{label}: extinct_at {result['extinct_at']} != {expected['extinct_at']}"
        )
    if result["peak_population"] != expected["peak_population"]:
        errors.append(
            f"{label}: peak {result['peak_population']} != {expected['peak_population']}"
        )
    got_history = result["history"]
    if len(got_history) != len(expected["history"]):
        errors.append(
            f"{label}: history length {len(got_history)} != {len(expected['history'])}"
        )
        return errors
    for got, want in zip(got_history, expected["history"]):
        if got["generation"] != want["generation"]:
            errors.append(
                f"{label}: generation {got['generation']} != {want['generation']}"
            )
        if got["population"] != want["population"]:
            errors.append(
                f"{label}: population@gen{want['generation']} {got['population']} != {want['population']}"
            )
        if abs(got["mean_fitness"] - want["mean_fitness"]) > TOLERANCE:
            errors.append(
                f"{label}: fitness@gen{want['generation']} {got['mean_fitness']} != {want['mean_fitness']}"
            )
        if got["events"] != want["events"]:
            errors.append(
                f"{label}: events@gen{want['generation']} {got['events']} != {want['events']}"
            )
    return errors


def run_rust(fixture: dict) -> dict | None:
    """Run the Rust CLI if it built; None when unavailable (no linker)."""
    binary_names = ["ecology.exe", "ecology"]
    for name in binary_names:
        candidate = (
            Path(__file__).parents[2]
            / "crates"
            / "ecology"
            / "target"
            / "release"
            / name
        )
        if candidate.exists():
            proc = subprocess.run(
                [str(candidate)],
                input=json.dumps(fixture["input"]),
                capture_output=True,
                text=True,
                check=True,
            )
            return json.loads(proc.stdout)
    built = subprocess.run(
        [
            "cargo",
            "build",
            "--release",
            "--manifest-path",
            str(Path(__file__).parents[2] / "crates" / "ecology" / "Cargo.toml"),
        ],
        capture_output=True,
        text=True,
    )
    if built.returncode != 0:
        return None
    binary = (
        Path(__file__).parents[2]
        / "crates"
        / "ecology"
        / "target"
        / "release"
        / "ecology.exe"
    )
    if not binary.exists():
        binary = (
            Path(__file__).parents[2]
            / "crates"
            / "ecology"
            / "target"
            / "release"
            / "ecology"
        )
    if not binary.exists():
        return None
    proc = subprocess.run(
        [str(binary)],
        input=json.dumps(fixture["input"]),
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(proc.stdout)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--rust", action="store_true", help="also diff the rust engine (needs a linker)"
    )
    args = parser.parse_args()

    fixtures = load_fixtures()
    failures: list[str] = []
    print(f"parity: {len(fixtures)} fixtures vs typescript reference")
    for fixture in fixtures:
        name = fixture["name"]
        py_result = run_python(fixture).to_dict()
        failures.extend(compare(py_result, fixture["expected"], f"python/{name}"))

        if args.rust:
            rust_result = run_rust(fixture)
            if rust_result is None:
                print(f"  rust/{name}: skipped (no linker on this machine)")
            else:
                failures.extend(
                    compare(rust_result, fixture["expected"], f"rust/{name}")
                )
        print(
            f"  python/{name}: outcome={py_result['outcome']} peak={py_result['peak_population']}"
        )

    if failures:
        print("\nPARITY FAILURES:")
        for failure in failures:
            print(f"  - {failure}")
        return 1
    print("\nparity: OK — python engine matches the typescript reference")
    return 0


if __name__ == "__main__":
    sys.exit(main())
